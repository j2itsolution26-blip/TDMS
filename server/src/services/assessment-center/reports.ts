import type { Prisma } from '@prisma/client';
import { prisma } from '@/server/lib/prisma';
import type { AuthUser } from '@shared/types/domain';
import { RESULT_LABELS, batchTotals, combineTotals, officialResult } from '@shared/lib/assessment-center';
import { studentName } from '@shared/lib/teaching-labels';
import { recordAudit, actorLabel, type AuditContext } from '../audit-log';
import type { ReportFilters } from '@/server/schemas/assessment-center';

/**
 * Batch result reports — the printable page and the CSV export are built from
 * this one function, so an export always matches the filters on screen.
 *
 * Per batch, one line per candidate: their latest attempt in that batch,
 * shown as Competent / Not Yet Competent only once finalized (Pending
 * otherwise). Totals and the competency rate count finalized results only,
 * computed here from the database.
 */

const day = (key: string) => new Date(`${key}T00:00:00Z`);
const dayOut = (d: Date) => d.toISOString().slice(0, 10);

/** The assessment center named on every report. Configured per deployment. */
export function centerInfo() {
  return {
    name: process.env.ASSESSMENT_CENTER_NAME?.trim() || 'Asian College of Science and Technology — TVET Assessment Center',
    address: process.env.ASSESSMENT_CENTER_ADDRESS?.trim() || null,
    accreditationNo: process.env.ASSESSMENT_CENTER_ACCREDITATION_NO?.trim() || null,
  };
}

export async function buildReport(f: ReportFilters, user: AuthUser) {
  const where: Prisma.AssessmentBatchWhereInput = { status: { not: 'CANCELLED' } };
  if (f.batchId) where.id = f.batchId;
  if (f.programId) where.programId = f.programId;
  if (f.assessor) where.assessorName = { contains: f.assessor, mode: 'insensitive' };
  if (f.from || f.to) where.assessmentDate = { ...(f.from ? { gte: day(f.from) } : {}), ...(f.to ? { lte: day(f.to) } : {}) };

  const batches = await prisma.assessmentBatch.findMany({
    where,
    orderBy: [{ assessmentDate: 'asc' }, { batchNumber: 'asc' }],
    take: 200,
    include: {
      program: { select: { code: true, name: true } },
      results: {
        where: { status: { not: 'CANCELLED' } },
        include: { student: { select: { studentNumber: true, firstName: true, middleName: true, lastName: true } } },
      },
    },
  });

  const sections = batches.map((b) => {
    // Latest attempt per candidate in this batch.
    const latest = new Map<string, (typeof b.results)[number]>();
    for (const r of b.results) {
      const key = r.studentId.toString();
      const seen = latest.get(key);
      if (!seen || r.attempt > seen.attempt) latest.set(key, r);
    }
    const rows = [...latest.values()]
      .sort((x, y) => x.student.lastName.localeCompare(y.student.lastName) || x.student.firstName.localeCompare(y.student.firstName))
      .map((r) => {
        const official = officialResult(r) ?? 'PENDING';
        return {
          candidateId: r.student.studentNumber,
          name: studentName(r.student),
          assessorName: b.assessorName,
          result: official,
          resultLabel: official === 'PENDING' ? RESULT_LABELS.PENDING : `${RESULT_LABELS[official]} (${official})`,
          attempt: r.attempt,
        };
      });
    return {
      batchId: b.id.toString(),
      batchNumber: b.batchNumber,
      qualification: { code: b.program.code, name: b.program.name },
      assessmentDate: dayOut(b.assessmentDate),
      assessorName: b.assessorName,
      venue: b.venue,
      status: b.status,
      rows,
      totals: batchTotals(b.results.map((r) => ({ studentId: r.studentId.toString(), attempt: r.attempt, status: r.status, result: r.result }))),
    };
  });

  return {
    center: centerInfo(),
    filters: f,
    generatedAt: new Date().toISOString(),
    generatedBy: user.name,
    batches: sections,
    totals: combineTotals(sections.map((s) => s.totals)),
    truncated: batches.length === 200,
  };
}
export type Report = Awaited<ReturnType<typeof buildReport>>;

function csvCell(value: unknown): string {
  const text = value === null || value === undefined ? '' : String(value);
  // Quote everything that needs it, and neutralise spreadsheet formulas.
  const safe = /^[=+\-@\t\r]/.test(text) ? `'${text}` : text;
  return /[",\r\n]/.test(safe) ? `"${safe.replace(/"/g, '""')}"` : safe;
}

/** CSV with a UTF-8 BOM so Excel opens accented names correctly. */
export function reportToCsv(report: Report): string {
  const lines: string[][] = [
    ['Assessment Center', report.center.name],
    ...(report.center.address ? [['Address', report.center.address]] : []),
    ...(report.center.accreditationNo ? [['Accreditation No.', report.center.accreditationNo]] : []),
    ['Report generated', report.generatedAt],
    ['Generated by', report.generatedBy],
    [],
    ['Batch', 'Qualification', 'Assessment Date', 'Candidate ID', 'Full Name', 'Assessor', 'Result', 'Attempt'],
  ];
  for (const b of report.batches) {
    for (const r of b.rows) {
      lines.push([b.batchNumber, `${b.qualification.code} — ${b.qualification.name}`, b.assessmentDate, r.candidateId, r.name, r.assessorName, r.resultLabel, String(r.attempt)]);
    }
  }
  lines.push([]);
  lines.push(['Batch', 'Assessed (finalized)', 'Competent', 'Not Yet Competent', 'Pending', 'Competency %']);
  for (const b of report.batches) {
    lines.push([b.batchNumber, String(b.totals.assessed), String(b.totals.competent), String(b.totals.notYetCompetent), String(b.totals.pending), b.totals.competentRate === null ? '' : String(b.totals.competentRate)]);
  }
  const t = report.totals;
  lines.push(['All batches', String(t.assessed), String(t.competent), String(t.notYetCompetent), String(t.pending), t.competentRate === null ? '' : String(t.competentRate)]);
  return `﻿${lines.map((l) => l.map(csvCell).join(',')).join('\r\n')}\r\n`;
}

export async function auditReport(kind: 'printed' | 'exported', report: Report, user: AuthUser, context: AuditContext) {
  await recordAudit({
    action: kind === 'printed' ? 'ASSESSMENT_REPORT_GENERATED' : 'ASSESSMENT_REPORT_EXPORTED',
    actor: actorLabel(user),
    target: 'Assessment batch result report',
    details: {
      // Ids are BigInt, which a JSON column cannot hold.
      filters: Object.fromEntries(Object.entries(report.filters).filter(([, v]) => v !== undefined && v !== null).map(([k, v]) => [k, String(v)])),
      batches: report.batches.map((b) => b.batchNumber),
      totals: report.totals,
    },
    context,
  });
}
